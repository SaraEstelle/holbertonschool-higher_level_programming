#!/usr/bin/node
// On déclare une constante appelée "myVar" et on lui assigne la valeur "JavaScript is amazing"
// "const" signifie que la variable ne peut pas être réassignée (contrairement à "var" ou "let")
const myVar = 'JavaScript is amazing';

// On affiche le contenu de "myVar" dans la console
// console.log() est la fonction standard pour afficher du texte en JavaScript
console.log(myVar);
